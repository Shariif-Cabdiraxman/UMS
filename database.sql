-- ---------------------------------------------------------------------
-- 0. DATABASE
-- ---------------------------------------------------------------------
CREATE DATABASE IF NOT EXISTS `university_management`
    DEFAULT CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE `university_management`;

-- Start from a clean slate so the file can be re-imported safely.
SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS `grades`;
DROP TABLE IF EXISTS `enrollments`;
DROP TABLE IF EXISTS `announcements`;
DROP TABLE IF EXISTS `courses`;
DROP TABLE IF EXISTS `student_accounts`;
DROP TABLE IF EXISTS `students`;
DROP TABLE IF EXISTS `lecturers`;
DROP TABLE IF EXISTS `departments`;
DROP TABLE IF EXISTS `faculties`;
DROP TABLE IF EXISTS `users`;
SET FOREIGN_KEY_CHECKS = 1;


-- ---------------------------------------------------------------------
-- 1. USERS
--    Staff accounts that can sign in to the administration platform.
--    Passwords are stored only as bcrypt hashes produced by
--    password_hash(). The seed file ships no usable password.
-- ---------------------------------------------------------------------
CREATE TABLE `users` (
    `id`            INT UNSIGNED    NOT NULL AUTO_INCREMENT,
    `username`      VARCHAR(50)     NOT NULL,
    `email`         VARCHAR(150)    NOT NULL,
    `password_hash` VARCHAR(255)    NOT NULL,
    `full_name`     VARCHAR(120)    NOT NULL,
    `role`          ENUM('admin','registrar') NOT NULL DEFAULT 'registrar',
    `status`        ENUM('active','inactive')   NOT NULL DEFAULT 'active',
    `last_login_at` DATETIME        NULL DEFAULT NULL,
    `created_at`    TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`    TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_users_username` (`username`),
    UNIQUE KEY `uq_users_email` (`email`),
    KEY `idx_users_role` (`role`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


-- ---------------------------------------------------------------------
-- 2. FACULTIES
--    The top level of the academic structure.
--    dean_id is added as a foreign key in section 11, after the
--    lecturers table exists (a dean is always a member of staff).
-- ---------------------------------------------------------------------
CREATE TABLE `faculties` (
    `id`          INT UNSIGNED  NOT NULL AUTO_INCREMENT,
    `code`        VARCHAR(20)   NOT NULL,
    `name`        VARCHAR(150)  NOT NULL,
    `description` TEXT          NULL DEFAULT NULL,
    `dean_id`     INT UNSIGNED  NULL DEFAULT NULL,
    `created_at`  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_faculties_code` (`code`),
    KEY `idx_faculties_dean` (`dean_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


-- ---------------------------------------------------------------------
-- 3. DEPARTMENTS
--    Every department MUST belong to exactly one faculty.
--    head_id is added as a foreign key in section 11.
-- ---------------------------------------------------------------------
CREATE TABLE `departments` (
    `id`          INT UNSIGNED  NOT NULL AUTO_INCREMENT,
    `code`        VARCHAR(20)   NOT NULL,
    `name`        VARCHAR(150)  NOT NULL,
    `faculty_id`  INT UNSIGNED  NOT NULL,
    `head_id`     INT UNSIGNED  NULL DEFAULT NULL,
    `description` TEXT          NULL DEFAULT NULL,
    `created_at`  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_departments_code` (`code`),
    KEY `idx_departments_faculty` (`faculty_id`),
    KEY `idx_departments_head` (`head_id`),
    CONSTRAINT `fk_departments_faculty`
        FOREIGN KEY (`faculty_id`) REFERENCES `faculties` (`id`)
        ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


-- ---------------------------------------------------------------------
-- 4. LECTURERS
--    Academic staff. Every lecturer belongs to one department.
-- ---------------------------------------------------------------------
CREATE TABLE `lecturers` (
    `id`            INT UNSIGNED   NOT NULL AUTO_INCREMENT,
    `staff_no`      VARCHAR(20)    NOT NULL,
    `first_name`    VARCHAR(60)    NOT NULL,
    `last_name`     VARCHAR(60)    NOT NULL,
    `email`         VARCHAR(150)   NOT NULL,
    `phone`         VARCHAR(30)    NULL DEFAULT NULL,
    `department_id` INT UNSIGNED   NOT NULL,
    `specialization` VARCHAR(150)  NULL DEFAULT NULL,
    `status`        ENUM('active','on_leave','inactive') NOT NULL DEFAULT 'active',
    `created_at`    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_lecturers_staff_no` (`staff_no`),
    UNIQUE KEY `uq_lecturers_email` (`email`),
    KEY `idx_lecturers_department` (`department_id`),
    KEY `idx_lecturers_status` (`status`),
    KEY `idx_lecturers_name` (`last_name`, `first_name`),
    CONSTRAINT `fk_lecturers_department`
        FOREIGN KEY (`department_id`) REFERENCES `departments` (`id`)
        ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


-- ---------------------------------------------------------------------
-- 5. STUDENTS
--    Enrollment year is the year the student first registered.
--    enrollment_date is the exact registration date and is what the
--    dashboard's 12-month enrollment trend is built from.
-- ---------------------------------------------------------------------
CREATE TABLE `students` (
    `id`              INT UNSIGNED    NOT NULL AUTO_INCREMENT,
    `student_no`      VARCHAR(20)     NOT NULL,
    `first_name`      VARCHAR(60)     NOT NULL,
    `last_name`       VARCHAR(60)     NOT NULL,
    `gender`          ENUM('male','female','other') NOT NULL,
    `date_of_birth`   DATE            NOT NULL,
    `email`           VARCHAR(150)    NOT NULL,
    `phone`           VARCHAR(30)     NULL DEFAULT NULL,
    `faculty_id`      INT UNSIGNED    NOT NULL,
    `department_id`   INT UNSIGNED    NOT NULL,
    `enrollment_year` SMALLINT UNSIGNED NOT NULL,
    `enrollment_date` DATE            NOT NULL,
    `status`          ENUM('active','inactive','graduated','suspended') NOT NULL DEFAULT 'active',
    `created_at`      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_students_student_no` (`student_no`),
    UNIQUE KEY `uq_students_email` (`email`),
    KEY `idx_students_department` (`department_id`),
    KEY `idx_students_faculty` (`faculty_id`),
    KEY `idx_students_status` (`status`),
    KEY `idx_students_year` (`enrollment_year`),
    KEY `idx_students_name` (`last_name`, `first_name`),
    CONSTRAINT `fk_students_faculty`
        FOREIGN KEY (`faculty_id`) REFERENCES `faculties` (`id`)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT `fk_students_department`
        FOREIGN KEY (`department_id`) REFERENCES `departments` (`id`)
        ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


-- ---------------------------------------------------------------------
-- 5b. STUDENT ACCOUNTS
--     A student signs in with their student number or student email. The
--     account is deliberately separate from the staff `users` table so a
--     student can never inherit a staff role, and deleting a student removes
--     the matching sign-in automatically.
-- ---------------------------------------------------------------------
CREATE TABLE `student_accounts` (
    `id`            INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `student_id`    INT UNSIGNED NOT NULL,
    `password_hash` VARCHAR(255) NOT NULL,
    `status`        ENUM('active','inactive') NOT NULL DEFAULT 'active',
    `last_login_at` DATETIME     NULL DEFAULT NULL,
    `created_at`    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_student_accounts_student` (`student_id`),
    KEY `idx_student_accounts_status` (`status`),
    CONSTRAINT `fk_student_accounts_student`
        FOREIGN KEY (`student_id`) REFERENCES `students` (`id`)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


-- ---------------------------------------------------------------------
-- 6. COURSES
--    course_code is UNIQUE - the database itself rejects a duplicate
--    course code, not just the application layer.
-- ---------------------------------------------------------------------
CREATE TABLE `courses` (
    `id`            INT UNSIGNED  NOT NULL AUTO_INCREMENT,
    `course_code`   VARCHAR(20)   NOT NULL,
    `course_name`   VARCHAR(180)  NOT NULL,
    `department_id` INT UNSIGNED  NOT NULL,
    `credit_hours`  TINYINT UNSIGNED NOT NULL DEFAULT 3,
    `semester`      ENUM('Semester 1','Semester 2') NOT NULL,
    `lecturer_id`   INT UNSIGNED  NULL DEFAULT NULL,
    `description`   TEXT          NULL DEFAULT NULL,
    `created_at`    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_courses_code` (`course_code`),
    KEY `idx_courses_department` (`department_id`),
    KEY `idx_courses_lecturer` (`lecturer_id`),
    KEY `idx_courses_semester` (`semester`),
    CONSTRAINT `fk_courses_department`
        FOREIGN KEY (`department_id`) REFERENCES `departments` (`id`)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT `fk_courses_lecturer`
        FOREIGN KEY (`lecturer_id`) REFERENCES `lecturers` (`id`)
        ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


-- ---------------------------------------------------------------------
-- 7. ENROLLMENTS
--    A student may take many courses; a course may hold many students.
--
--    The composite UNIQUE key is the important part of this table: it
--    makes it impossible to register the same student for the same
--    course twice within one semester of one academic year, no matter
--    what the application does.
-- ---------------------------------------------------------------------
CREATE TABLE `enrollments` (
    `id`              INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `student_id`      INT UNSIGNED NOT NULL,
    `course_id`       INT UNSIGNED NOT NULL,
    `academic_year`   VARCHAR(9)   NOT NULL,          -- format: YYYY/YYYY
    `semester`        ENUM('Semester 1','Semester 2') NOT NULL,
    `enrollment_date` DATE         NOT NULL,
    `status`          ENUM('enrolled','completed','dropped','failed') NOT NULL DEFAULT 'enrolled',
    `created_at`      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_enrollments_unique` (`student_id`, `course_id`, `academic_year`, `semester`),
    KEY `idx_enrollments_course` (`course_id`),
    KEY `idx_enrollments_term` (`academic_year`, `semester`),
    KEY `idx_enrollments_status` (`status`),
    KEY `idx_enrollments_date` (`enrollment_date`),
    CONSTRAINT `fk_enrollments_student`
        FOREIGN KEY (`student_id`) REFERENCES `students` (`id`)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT `fk_enrollments_course`
        FOREIGN KEY (`course_id`) REFERENCES `courses` (`id`)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


-- ---------------------------------------------------------------------
-- 8. GRADES
--    A grade always belongs to an enrollment, never directly to a
--    student or a course. This is what guarantees you cannot record a
--    mark for a student who was never registered for the course - the
--    student, course, academic year and semester are all derived by
--    JOINing the enrollment instead of being copied here.
--
--    letter_grade is stored (rather than only computed) so it can be
--    indexed, filtered and aggregated in SQL. The application recalculates
--    it from `marks` on every insert and update.
-- ---------------------------------------------------------------------
CREATE TABLE `grades` (
    `id`            INT UNSIGNED  NOT NULL AUTO_INCREMENT,
    `enrollment_id` INT UNSIGNED  NOT NULL,
    `assessment`    VARCHAR(120)  NOT NULL,
    `marks`         DECIMAL(5,2)  NOT NULL,
    `letter_grade`  ENUM('A','B','C','D','F') NOT NULL,
    `created_at`    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_grades_enrollment_assessment` (`enrollment_id`, `assessment`),
    KEY `idx_grades_letter` (`letter_grade`),
    KEY `idx_grades_marks` (`marks`),
    CONSTRAINT `fk_grades_enrollment`
        FOREIGN KEY (`enrollment_id`) REFERENCES `enrollments` (`id`)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT `chk_grades_marks` CHECK (`marks` >= 0 AND `marks` <= 100)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


-- ---------------------------------------------------------------------
-- 9. ANNOUNCEMENTS
--    Only rows with status='published' and a published_at timestamp are
--    ever shown as news; drafts stay invisible to the dashboard feed.
-- ---------------------------------------------------------------------
CREATE TABLE `announcements` (
    `id`           INT UNSIGNED  NOT NULL AUTO_INCREMENT,
    `title`        VARCHAR(180)  NOT NULL,
    `content`      TEXT          NOT NULL,
    `status`       ENUM('draft','published','archived') NOT NULL DEFAULT 'draft',
    `published_at` DATETIME      NULL DEFAULT NULL,
    `author_id`    INT UNSIGNED  NOT NULL,
    `created_at`   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    KEY `idx_announcements_status_date` (`status`, `published_at`),
    KEY `idx_announcements_author` (`author_id`),
    CONSTRAINT `fk_announcements_author`
        FOREIGN KEY (`author_id`) REFERENCES `users` (`id`)
        ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


-- ---------------------------------------------------------------------
-- 10. LATE FOREIGN KEYS (circular staff references)
--
--     faculties.dean_id        -> lecturers.id
--     departments.head_id      -> lecturers.id
--
--     Both are "who is in charge" pointers, and both point at a member
--     of staff. Because lecturers.department_id already points back up
--     the tree, the two tables reference each other. MySQL cannot create
--     that cycle inside a single CREATE TABLE, so the constraints are
--     attached here, after both tables exist.
--
--     ON DELETE SET NULL: if a dean or head is ever deleted, the
--     department survives with the post temporarily vacant.
-- ---------------------------------------------------------------------
ALTER TABLE `faculties`
    ADD CONSTRAINT `fk_faculties_dean`
        FOREIGN KEY (`dean_id`) REFERENCES `lecturers` (`id`)
        ON DELETE SET NULL ON UPDATE CASCADE;

ALTER TABLE `departments`
    ADD CONSTRAINT `fk_departments_head`
        FOREIGN KEY (`head_id`) REFERENCES `lecturers` (`id`)
        ON DELETE SET NULL ON UPDATE CASCADE;

